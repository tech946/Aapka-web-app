import type { ReactNode } from 'react';

export interface Column<T> {
  key: string;
  header: string;
  render: (row: T) => ReactNode;
  className?: string;
}

interface DataTableProps<T> {
  columns: Column<T>[];
  rows: T[];
  rowKey: (row: T) => string;
  loading?: boolean;
  error?: string | null;
  emptyMessage?: ReactNode;
}

export function DataTable<T>({ columns, rows, rowKey, loading, error, emptyMessage = 'Nothing here yet.' }: DataTableProps<T>) {
  const status = loading ? 'Loading…' : error ? error : rows.length === 0 ? emptyMessage : null;

  return (
    <div className='table_wrapper'>
      <table className='table'>
        <thead>
          <tr>
            {columns.map((c) => (
              <th key={c.key} className={c.className}>
                {c.header}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {status ? (
            <tr>
              <td className='table_empty' colSpan={columns.length}>
                {status}
              </td>
            </tr>
          ) : (
            rows.map((row) => (
              <tr key={rowKey(row)}>
                {columns.map((c) => (
                  <td key={c.key} className={c.className}>
                    {c.render(row)}
                  </td>
                ))}
              </tr>
            ))
          )}
        </tbody>
      </table>
    </div>
  );
}
